export async function renderWorkOrders(host) {
  const root = freshRoot(host);
  const header = pageIntro({
    eyebrow: "Work management",
    title: "Work orders",
    subtitle:
      "Assign technicians, track progress, and close requests with a documented repair.",
    badge: "Live queue",
  });

  root.innerHTML = header + skeletonGrid(3);

  let issues;
  let technicians;
  try {
    [issues, technicians] = await Promise.all([api.issues(), api.technicians()]);
  } catch (error) {
    root.innerHTML = header + loadError(error, "work orders");
    return;
  }

  if (issues.length === 0) {
    root.innerHTML =
      header +
      emptyState("No work orders yet", "Report an equipment issue to create one.") +
      `<div class="mt-2"><a class="btn btn-primary" href="#/report">${ICON.plus} Report an issue</a></div>`;
    return;
  }

  const filters = { status: "", priority: "", search: "" };

  root.innerHTML =
    header +
    `
    <div class="filters">
      <div class="field">
        <label for="f-status">Status</label>
        ${selectHtml("status", [{ value: "", label: "All statuses" }].concat(
          STATUS_OPTIONS.map((status) => ({ value: status, label: status }))
        ), { id: "f-status" })}
      </div>
      <div class="field">
        <label for="f-priority">Priority</label>
        ${selectHtml("priority", [{ value: "", label: "All priorities" }].concat(
          PRIORITY_OPTIONS.map((priority) => ({ value: priority, label: priority }))
        ), { id: "f-priority" })}
      </div>
      <div class="field" style="flex:1;min-width:200px">
        <label for="f-search">Search</label>
        <input id="f-search" type="search" placeholder="Equipment, issue, or technician">
      </div>
    </div>
    <div id="wo-list"></div>`;

  const list = root.querySelector("#wo-list");

  const draw = () => {
    const terms = filters.search.toLowerCase();
    const visible = issues.filter((issue) => {
      if (filters.status && issue.status !== filters.status) return false;
      if (filters.priority && issue.priority !== filters.priority) return false;
      if (!terms) return true;
      return [issue.title, issue.equipment, issue.technician, issue.description]
        .join(" ")
        .toLowerCase()
        .includes(terms);
    });

    list.innerHTML = visible.length
      ? visible.map((issue) => workOrderHtml(issue, technicians)).join("")
      : emptyState("No matching work orders", "Try clearing the filters.");
  };

  draw();

  root.querySelector("#f-status").addEventListener("change", (event) => {
    filters.status = event.target.value;
    draw();
  });
  root.querySelector("#f-priority").addEventListener("change", (event) => {
    filters.priority = event.target.value;
    draw();
  });
  root.querySelector("#f-search").addEventListener("input", (event) => {
    filters.search = event.target.value;
    draw();
  });

  list.addEventListener("click", (event) => {
    const toggle = event.target.closest("[data-toggle]");
    if (!toggle) return;
    const card = toggle.closest(".wo");
    const isOpen = card.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", String(isOpen));
  });

  list.addEventListener("submit", async (event) => {
    const form = event.target;
    if (!(form instanceof HTMLFormElement)) return;
    event.preventDefault();
    const values = formValues(form);
    const button = form.querySelector('button[type="submit"]');

    if (form.dataset.update) {
      const issueId = Number(form.dataset.update);
      try {
        await withBusy(
          button,
          () =>
            api.updateIssue(issueId, {
              status: values.status,
              technician_id: values.technician_id === "" ? null : Number(values.technician_id),
            }),
          "Saving…"
        );
      } catch (error) {
        toast(error.message, { type: "error", title: "Not saved" });
        return;
      }
      toast(`Work order #${issueId} updated.`, { type: "success" });
      await renderWorkOrders(host);
      return;
    }

    if (form.dataset.record) {
      const issueId = Number(form.dataset.record);
      if (!values.work_performed || values.work_performed.length === 0) {
        toast("Describe the work performed before saving.", { type: "error" });
        return;
      }
      try {
        await withBusy(
          button,
          () =>
            api.closeIssue(issueId, {
              work_performed: values.work_performed,
              parts_used: values.parts_used || "",
              duration_hours: Number(values.duration_hours) || 0,
              technician_id: values.technician_id === "" ? null : Number(values.technician_id),
            }),
          "Saving…"
        );
      } catch (error) {
        toast(error.message, { type: "error", title: "Not saved" });
        return;
      }
      toast(`Maintenance record saved and request #${issueId} closed.`, { type: "success" });
      await renderWorkOrders(host);
    }
  });
}

