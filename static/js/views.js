/**
 * The seven MaintainIQ views. Each `render*(host)` call builds a fresh root
 * element so previously attached listeners are discarded on re-render.
 */

import { api } from "./api.js?v=5";
import {
  ICON, STAT_ICONS, alertBox, attr, bars, countUp, donut, emptyState, esc,
  formValues, formatDate, formatDateTime, healthChip, neutralChip, openModal,
  pageIntro, priorityChip, sectionHead, skeletonCard, statusChip, table, toast,
  truncate, withBusy,
} from "./ui.js?v=5";

/* --- Shared helpers ---------------------------------------------------- */

function freshRoot(host) {
  host.replaceChildren();
  const root = document.createElement("div");
  host.appendChild(root);
  return root;
}

function skeletonGrid(count = 4) {
  return `<div class="grid grid-4">${Array.from({ length: count }, () => skeletonCard(2)).join("")}</div>`;
}

function loadError(error, what) {
  return alertBox(
    "error",
    `<strong>Could not load ${esc(what)}.</strong><br>${esc(error.message)}`
  );
}

function statCard(kind, label, value, meta, isAlert = false) {
  return `
    <div class="stat">
      <div class="stat-label">${STAT_ICONS[kind] || ICON.info}${esc(label)}</div>
      <div class="stat-value" data-count="${Number(value) || 0}">0</div>
      <div class="stat-meta${isAlert ? " is-alert" : ""}">${esc(meta)}</div>
    </div>`;
}

function wireCounters(root) {
  root.querySelectorAll("[data-count]").forEach((node) => {
    countUp(node, Number(node.dataset.count) || 0);
  });
}

function selectHtml(name, options, { selected = "", id = "" } = {}) {
  const rendered = options
    .map((option) => {
      const isSelected = String(option.value) === String(selected);
      return `<option value="${attr(option.value)}"${isSelected ? " selected" : ""}>${esc(option.label)}</option>`;
    })
    .join("");
  return `<select name="${attr(name)}"${id ? ` id="${attr(id)}"` : ""}>${rendered}</select>`;
}

function equipmentOptionsHtml(equipment) {
  return equipment.map((item) => ({
    value: item.id,
    label: `${item.name} — ${item.equipment_type} (${item.location || "Location not set"})`,
  }));
}

const STATUS_OPTIONS = ["Open", "In Progress", "On Hold", "Closed"];
const PRIORITY_OPTIONS = ["Critical", "High", "Medium", "Low"];

function technicianSelectOptions(technicians, { unassignedLabel = "Unassigned" } = {}) {
  return [{ value: "", label: unassignedLabel }].concat(
    technicians.map((tech) => ({ value: tech.id, label: tech.name }))
  );
}

function workloadChip(count) {
  const tone = count === 0 ? "mint" : count <= 2 ? "amber" : "red";
  return `<span class="chip chip-${tone} chip-plain">${count} active</span>`;
}

/** Provider footnote shared by the triage and assistant views. */
function providerNote(configured) {
  return configured
    ? alertBox(
        "info",
        "Groq AI is configured. Issue triage, technician routing, and knowledge answers are generated by the model, then validated against your equipment and roster data."
      )
    : alertBox(
        "warn",
        "Groq AI is not configured, so this workspace uses local rules-based triage and documented-skill matching. Set <strong>GROQ_API_KEY</strong> in <code>.streamlit/secrets.toml</code> (or the environment) and restart the server to enable AI-generated analysis."
      );
}

