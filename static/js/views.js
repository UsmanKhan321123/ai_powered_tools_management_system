export async function renderReport(host) {
  const root = freshRoot(host);
  const header = pageIntro({
    eyebrow: "Request intake",
    title: "Report an issue",
    subtitle:
      "Describe what happened. AI triage will help prioritise and route the request.",
    badge: "AI-assisted triage",
  });

  root.innerHTML = header + skeletonGrid(2);

  let equipment;
  let status;
  try {
    [equipment, status] = await Promise.all([api.equipment(), api.status()]);
  } catch (error) {
    root.innerHTML = header + loadError(error, "the intake form");
    return;
  }

  if (equipment.length === 0) {
    root.innerHTML =
      header +
      alertBox(
        "warn",
        `<strong>No equipment registered.</strong> Add equipment before reporting an issue.`
      ) +
      `<a class="btn btn-primary" href="#/equipment">${ICON.plus} Add equipment</a>`;
    return;
  }

  root.innerHTML =
    header +
    `
    <div class="split">
      <div class="card">
        <h3>Describe the problem</h3>
        <p class="section-note">Include what you saw, heard, or smelled, and when it started.</p>
        <form id="report-form" novalidate>
          <div class="field">
            <label for="asset">Equipment</label>
            ${selectHtml("equipment_id", equipmentOptionsHtml(equipment), { id: "asset" })}
          </div>
          <div class="field">
            <label for="desc">Describe the problem</label>
            <textarea id="desc" name="description" placeholder="Example: CNC-001 is overheating and making unusual noise."></textarea>
            <span class="field-hint">At least 8 characters. Specific symptoms improve routing accuracy.</span>
          </div>
          <button class="btn btn-primary btn-block" type="submit">${ICON.sparkles} Analyze &amp; create request</button>
        </form>
        <div class="mt-2">${providerNote(status.groq_configured)}</div>
      </div>

      <div id="triage-result">
        ${emptyState("Awaiting analysis", "Describe a fault and the triage result will appear here.")}
      </div>
    </div>`;

  const form = root.querySelector("#report-form");
  const resultPanel = root.querySelector("#triage-result");
  const submit = form.querySelector('button[type="submit"]');

  const submitTo = async (task, busyLabel) => {
    const original = submit.innerHTML;
    submit.disabled = true;
    submit.textContent = busyLabel;
    try {
      return await task();
    } finally {
      submit.disabled = false;
      submit.innerHTML = original;
    }
  };

  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const values = formValues(form);
    const description = values.description || "";
    if (description.length < 8) {
      toast("Please describe the problem in a little more detail.", { type: "error" });
      return;
    }

    let result;
    try {
      result = await submitTo(
        () =>
          api.previewTriage({
            equipment_id: Number(values.equipment_id),
            description,
          }),
        "Analyzing…"
      );
    } catch (error) {
      resultPanel.innerHTML = alertBox("error", `<strong>Triage failed.</strong><br>${esc(error.message)}`);
      return;
    }

    resultPanel.innerHTML = triageResultHtml(result);

    const confirmButton = resultPanel.querySelector("[data-confirm]");
    confirmButton.addEventListener("click", async () => {
      let created;
      try {
        created = await withBusy(
          confirmButton,
          () =>
            api.createIssue({
              equipment_id: Number(values.equipment_id),
              description,
            }),
          "Creating…"
        );
      } catch (error) {
        toast(error.message, { type: "error", title: "Not created" });
        return;
      }
      resultPanel.innerHTML = triageResultHtml(created, {
        committed: true,
        issueId: created.issue_id,
      });
      toast(`Request #${created.issue_id} created.`, { type: "success" });
    });
  });
}

